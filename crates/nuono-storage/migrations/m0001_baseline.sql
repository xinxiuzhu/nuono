    subject_user_id BIGINT REFERENCES nuono_users(id) ON DELETE RESTRICT,
    group_id BIGINT REFERENCES nuono_groups(id) ON DELETE RESTRICT,
    operation_id TEXT COLLATE "C",
    details_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (details_json::jsonb IS NOT NULL)
);

