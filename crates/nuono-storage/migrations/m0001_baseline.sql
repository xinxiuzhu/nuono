    actor_user_id BIGINT REFERENCES nuono_users(id) ON DELETE RESTRICT,
    actor_plugin_id TEXT COLLATE "C" REFERENCES nuono_plugins(plugin_id) ON DELETE RESTRICT CHECK (actor_plugin_id IS NULL OR octet_length(actor_plugin_id) BETWEEN 1 AND 64),
    actor_label TEXT COLLATE "C",
    bot_id TEXT COLLATE "C",
    action TEXT COLLATE "C" NOT NULL CHECK (length(action) <= 100),
