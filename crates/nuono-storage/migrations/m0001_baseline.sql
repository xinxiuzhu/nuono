    namespace TEXT COLLATE "C" NOT NULL,
    scope_key TEXT COLLATE "C" NOT NULL CHECK (length(scope_key) <= 64),
    scope_id TEXT COLLATE "C" NOT NULL,
    scene TEXT COLLATE "C" NOT NULL CHECK (length(scene) <= 16),
    plugin TEXT COLLATE "C" NOT NULL CHECK (length(plugin) <= 128),
    kind TEXT COLLATE "C" NOT NULL CHECK (length(kind) <= 16),
    count BIGINT NOT NULL CHECK (count > 0)
