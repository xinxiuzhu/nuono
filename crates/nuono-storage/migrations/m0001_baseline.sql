-- Nuono 核心基线表结构（PostgreSQL）。
-- 主键编号与 UTC Unix 毫秒时间统一使用有符号 64 位整数；落库 JSON 均经过校验。
-- 可选 AI / Agent / 陪伴模块表位于 ai_m0001_baseline.sql，按需启用时才创建。

CREATE TABLE nuono_schema_migrations (
    module TEXT COLLATE "C" NOT NULL DEFAULT 'core' CHECK (module IN ('core', 'ai')),
    version BIGINT NOT NULL CHECK (version > 0),
    description TEXT COLLATE "C" NOT NULL,
    checksum TEXT COLLATE "C" NOT NULL,
    applied_at_ms BIGINT NOT NULL,
    PRIMARY KEY (module, version)
);

CREATE TABLE nuono_deployment (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    deployment_id TEXT COLLATE "C" NOT NULL UNIQUE,
    maintenance_operation TEXT COLLATE "C",
    assets_json TEXT COLLATE "C" NOT NULL DEFAULT '[]' CHECK (assets_json::jsonb IS NOT NULL),
    created_at_ms BIGINT NOT NULL
);

CREATE TABLE nuono_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    account_kind TEXT COLLATE "C" NOT NULL DEFAULT 'registered' CHECK (account_kind IN ('shadow', 'registered')),
    username TEXT COLLATE "C",
    username_key TEXT COLLATE "C" UNIQUE,
    email TEXT COLLATE "C",
    email_key TEXT COLLATE "C" UNIQUE,
    email_verified_at_ms BIGINT,
    password_hash TEXT COLLATE "C",
    totp_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    totp_secret BYTEA,
    totp_recovery_json TEXT COLLATE "C" NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(totp_recovery_json::jsonb) = 'array'),
    totp_last_counter BIGINT CHECK (totp_last_counter >= 0),
    role TEXT COLLATE "C" NOT NULL DEFAULT 'user' CHECK (role IN ('owner', 'admin', 'user')),
    status TEXT COLLATE "C" NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled', 'merged', 'deleted')),
    merged_into_user_id BIGINT REFERENCES nuono_users(id),
    auth_epoch BIGINT NOT NULL DEFAULT 1 CHECK (auth_epoch > 0),
    last_login_at_ms BIGINT,
    display_name TEXT COLLATE "C" NOT NULL DEFAULT '',
    birthday TEXT COLLATE "C" NOT NULL DEFAULT '',
    gender TEXT COLLATE "C" NOT NULL DEFAULT '',
    bio TEXT COLLATE "C" NOT NULL DEFAULT '',
    use_for_ai BOOLEAN NOT NULL DEFAULT FALSE,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CHECK ((username IS NULL) = (username_key IS NULL)),
    CHECK (username_key IS NULL OR (length(username_key) BETWEEN 3 AND 64 AND username_key = lower(username) AND username_key ~ '^[a-z0-9_.-]+$')),
    CHECK ((email IS NULL) = (email_key IS NULL) AND (email IS NULL) = (email_verified_at_ms IS NULL)),
    CHECK (email_key IS NULL OR (email_key = lower(trim(email)) AND email_key <> '')),
    CHECK ((status = 'merged' AND merged_into_user_id IS NOT NULL AND merged_into_user_id <> id) OR (status <> 'merged' AND merged_into_user_id IS NULL)),
    CHECK (
        (account_kind = 'registered' AND status IN ('active', 'disabled') AND username IS NOT NULL AND password_hash IS NOT NULL)
        OR (account_kind = 'shadow' AND status IN ('active', 'disabled') AND username IS NULL AND email IS NULL AND password_hash IS NULL AND totp_secret IS NULL AND totp_enabled = FALSE AND totp_recovery_json = '[]' AND role = 'user')
        OR (status IN ('merged', 'deleted') AND username IS NULL AND email IS NULL AND password_hash IS NULL AND totp_secret IS NULL AND totp_enabled = FALSE AND totp_recovery_json = '[]' AND role = 'user' AND display_name = '' AND birthday = '' AND gender = '' AND bio = '' AND use_for_ai = FALSE)
    ),
    CHECK (totp_enabled = FALSE OR totp_secret IS NOT NULL)
);

CREATE TABLE nuono_platform_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    platform TEXT COLLATE "C" NOT NULL,
    namespace TEXT COLLATE "C" NOT NULL DEFAULT '',
    identity_kind TEXT COLLATE "C" NOT NULL,
    native_user_id TEXT COLLATE "C" NOT NULL,
    user_id BIGINT NOT NULL REFERENCES nuono_users(id) ON DELETE RESTRICT,
    verified_at_ms BIGINT,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    UNIQUE (platform, namespace, identity_kind, native_user_id),
    CHECK (octet_length(platform || namespace || identity_kind || native_user_id) <= 1024)
);

CREATE TABLE nuono_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    platform TEXT COLLATE "C" NOT NULL,
    namespace TEXT COLLATE "C" NOT NULL DEFAULT '',
    conversation_kind TEXT COLLATE "C" NOT NULL,
    native_parent_id TEXT COLLATE "C" NOT NULL DEFAULT '',
    native_group_id TEXT COLLATE "C" NOT NULL,
    display_name TEXT COLLATE "C" NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    UNIQUE (platform, namespace, conversation_kind, native_parent_id, native_group_id),
    CHECK (octet_length(platform || namespace || conversation_kind || native_parent_id || native_group_id) <= 1024)
);

CREATE TABLE nuono_plugins (
    plugin_id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (octet_length(plugin_id) BETWEEN 1 AND 64),
    plugin_role TEXT COLLATE "C" NOT NULL DEFAULT 'feature' CHECK (plugin_role IN ('feature', 'service')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    allow_user_overrides BOOLEAN NOT NULL DEFAULT FALSE,
    allow_group_overrides BOOLEAN NOT NULL DEFAULT FALSE,
    slow_threshold_ms BIGINT CHECK (slow_threshold_ms BETWEEN 0 AND 3600000),
    trigger_policy_json TEXT COLLATE "C" CHECK (trigger_policy_json IS NULL OR trigger_policy_json::jsonb IS NOT NULL),
    service_config_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (service_config_json::jsonb IS NOT NULL),
    config_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (config_json::jsonb IS NOT NULL),
    config_version BIGINT NOT NULL DEFAULT 1 CHECK (config_version > 0),
    table_prefix TEXT COLLATE "C" UNIQUE,
    schema_version BIGINT CHECK (schema_version > 0),
    code_version TEXT COLLATE "C",
    installed BOOLEAN NOT NULL DEFAULT FALSE,
    portable_manifest_json TEXT COLLATE "C",
    registry_updated_at_ms BIGINT,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CHECK (plugin_role <> 'service' OR (allow_user_overrides = FALSE AND allow_group_overrides = FALSE)),
    CHECK (table_prefix IS NULL OR (length(table_prefix) BETWEEN 2 AND 62 AND table_prefix ~ '^[a-z][a-z0-9]*(_[a-z0-9]+)*_$')),
    CHECK (portable_manifest_json IS NULL OR jsonb_typeof(portable_manifest_json::jsonb) = 'object'),
    CHECK ((table_prefix IS NULL) = (portable_manifest_json IS NULL)),
    CHECK ((table_prefix IS NULL) = (code_version IS NULL)),
    CHECK (schema_version IS NULL OR table_prefix IS NOT NULL)
);

CREATE TABLE nuono_plugin_migrations (
    plugin_id TEXT COLLATE "C" NOT NULL REFERENCES nuono_plugins(plugin_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    version BIGINT NOT NULL CHECK (version > 0),
    description TEXT COLLATE "C" NOT NULL,
    checksum TEXT COLLATE "C" NOT NULL,
    applied_at_ms BIGINT NOT NULL,
    PRIMARY KEY (plugin_id, version)
);

CREATE TABLE nuono_plugin_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    plugin_id TEXT COLLATE "C" NOT NULL REFERENCES nuono_plugins(plugin_id) ON DELETE RESTRICT CHECK (octet_length(plugin_id) BETWEEN 1 AND 64),
    user_id BIGINT REFERENCES nuono_users(id) ON DELETE RESTRICT,
    group_id BIGINT REFERENCES nuono_groups(id) ON DELETE RESTRICT,
    enabled BOOLEAN,
    service_patch_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (service_patch_json::jsonb IS NOT NULL),
    config_patch_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (config_patch_json::jsonb IS NOT NULL),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CHECK ((user_id IS NULL) <> (group_id IS NULL)),
    UNIQUE (plugin_id, user_id),
    UNIQUE (plugin_id, group_id)
);

CREATE TABLE nuono_entitlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    subject_type TEXT COLLATE "C" NOT NULL CHECK (subject_type IN ('group', 'user')),
    subject_id BIGINT NOT NULL CHECK (subject_id > 0),
    feature_key TEXT COLLATE "C" NOT NULL CHECK (octet_length(feature_key) BETWEEN 1 AND 128),
    source TEXT COLLATE "C" NOT NULL CHECK (source IN ('billing', 'manual', 'trial')),
    source_ref TEXT COLLATE "C" CHECK (source_ref IS NULL OR octet_length(source_ref) BETWEEN 1 AND 256),
    status TEXT COLLATE "C" NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
    starts_at_ms BIGINT NOT NULL,
    expires_at_ms BIGINT,
    limits_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(limits_json::jsonb) = 'object'),
    updated_at_ms BIGINT NOT NULL,
    CHECK (expires_at_ms IS NULL OR expires_at_ms > starts_at_ms)
);

CREATE TABLE nuono_group_authorizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    user_id BIGINT NOT NULL REFERENCES nuono_users(id) ON DELETE RESTRICT,
    group_id BIGINT NOT NULL REFERENCES nuono_groups(id) ON DELETE RESTRICT,
    capability TEXT COLLATE "C" NOT NULL DEFAULT 'manage_plugin_config' CHECK (capability = 'manage_plugin_config'),
    scope_kind TEXT COLLATE "C" NOT NULL CHECK (scope_kind IN ('all_plugins', 'one_plugin')),
    plugin_id TEXT COLLATE "C" REFERENCES nuono_plugins(plugin_id) ON DELETE RESTRICT CHECK (plugin_id IS NULL OR octet_length(plugin_id) BETWEEN 1 AND 64),
    issuer_kind TEXT COLLATE "C" NOT NULL CHECK (issuer_kind IN ('manual', 'plugin')),
    issuer_user_id BIGINT REFERENCES nuono_users(id) ON DELETE RESTRICT,
    issuer_plugin_id TEXT COLLATE "C" REFERENCES nuono_plugins(plugin_id) ON DELETE RESTRICT CHECK (issuer_plugin_id IS NULL OR octet_length(issuer_plugin_id) BETWEEN 1 AND 64),
    source_key TEXT COLLATE "C" NOT NULL CHECK (length(source_key) BETWEEN 1 AND 256 AND octet_length(source_key) BETWEEN 1 AND 256),
    valid_from_ms BIGINT NOT NULL,
    expires_at_ms BIGINT,
    revoked_at_ms BIGINT,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CHECK ((scope_kind = 'all_plugins' AND plugin_id IS NULL) OR (scope_kind = 'one_plugin' AND plugin_id IS NOT NULL)),
    CHECK (expires_at_ms IS NULL OR expires_at_ms > valid_from_ms),
    CHECK ((issuer_kind = 'manual' AND issuer_user_id IS NOT NULL AND issuer_plugin_id IS NULL) OR (issuer_kind = 'plugin' AND issuer_plugin_id IS NOT NULL AND issuer_user_id IS NULL)),
    UNIQUE (issuer_user_id, source_key),
    UNIQUE (issuer_plugin_id, source_key)
);

CREATE TABLE nuono_sessions (
    id TEXT COLLATE "C" PRIMARY KEY CHECK (id ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
    user_id BIGINT NOT NULL REFERENCES nuono_users(id),
    token_hash BYTEA NOT NULL UNIQUE CHECK (length(token_hash) = 32),
    auth_epoch BIGINT NOT NULL CHECK (auth_epoch > 0),
    created_at_ms BIGINT NOT NULL,
    expires_at_ms BIGINT NOT NULL,
    last_seen_at_ms BIGINT,
    revoked_at_ms BIGINT,
    CHECK (expires_at_ms > created_at_ms)
);

CREATE TABLE nuono_account_challenges (
    id TEXT COLLATE "C" PRIMARY KEY CHECK (id ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
    purpose TEXT COLLATE "C" NOT NULL CHECK (purpose IN ('registration', 'email_verification', 'email_change', 'password_reset', 'platform_binding', 'merge_proof')),
    requester_user_id BIGINT REFERENCES nuono_users(id),
    subject_user_id BIGINT REFERENCES nuono_users(id),
    subject_auth_epoch BIGINT,
    session_id TEXT COLLATE "C" REFERENCES nuono_sessions(id),
    token_hash BYTEA NOT NULL UNIQUE CHECK (length(token_hash) = 32),
    context_json TEXT COLLATE "C" NOT NULL CHECK (jsonb_typeof(context_json::jsonb) = 'object'),
    candidate_identity_id BIGINT REFERENCES nuono_platform_identities(id),
    state TEXT COLLATE "C" NOT NULL CHECK (state IN ('pending', 'candidate', 'consumed', 'cancelled', 'expired')),
    attempts BIGINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    expires_at_ms BIGINT NOT NULL,
    consumed_at_ms BIGINT,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CHECK ((subject_user_id IS NULL) = (subject_auth_epoch IS NULL)),
    CHECK (subject_auth_epoch IS NULL OR subject_auth_epoch > 0),
    CHECK (purpose IN ('platform_binding', 'registration') OR (candidate_identity_id IS NULL AND state <> 'candidate')),
    CHECK ((state = 'consumed') = (consumed_at_ms IS NOT NULL)),
    CHECK (expires_at_ms > created_at_ms)
);

CREATE TABLE nuono_account_merge_jobs (
    id TEXT COLLATE "C" PRIMARY KEY CHECK (id ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
    source_user_id BIGINT NOT NULL REFERENCES nuono_users(id),
    target_user_id BIGINT NOT NULL REFERENCES nuono_users(id),
    source_proof_id TEXT COLLATE "C" REFERENCES nuono_account_challenges(id),
    target_proof_id TEXT COLLATE "C" REFERENCES nuono_account_challenges(id),
    status TEXT COLLATE "C" NOT NULL CHECK (status IN ('preflight', 'ready', 'running', 'completed', 'failed', 'cancelled')),
    plan_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(plan_json::jsonb) = 'object'),
    failure_code TEXT COLLATE "C",
    completed_at_ms BIGINT,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CHECK (source_user_id <> target_user_id),
    CHECK ((status = 'completed') = (completed_at_ms IS NOT NULL))
);

CREATE TABLE nuono_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    user_id BIGINT NOT NULL,
    kind TEXT COLLATE "C" NOT NULL,
    title TEXT COLLATE "C" NOT NULL,
    body TEXT COLLATE "C" NOT NULL,
    link TEXT COLLATE "C",
    read_at BIGINT,
    created_at BIGINT NOT NULL
);

CREATE TABLE nuono_global_configs (
    key TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (octet_length(key) BETWEEN 1 AND 256),
    value_json TEXT COLLATE "C" NOT NULL CHECK (value_json::jsonb IS NOT NULL),
    value_version BIGINT NOT NULL DEFAULT 1 CHECK (value_version > 0),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL
);

CREATE TABLE nuono_runtime_secrets (
    key TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (octet_length(key) BETWEEN 1 AND 256),
    owner_plugin_id TEXT COLLATE "C" REFERENCES nuono_plugins(plugin_id) ON DELETE RESTRICT CHECK (owner_plugin_id IS NULL OR octet_length(owner_plugin_id) BETWEEN 1 AND 64),
    value BYTEA NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL
);

CREATE TABLE nuono_plugin_kv (
    plugin_id TEXT COLLATE "C" NOT NULL REFERENCES nuono_plugins(plugin_id) ON DELETE RESTRICT CHECK (octet_length(plugin_id) BETWEEN 1 AND 64),
    collection TEXT COLLATE "C" NOT NULL CHECK (octet_length(collection) BETWEEN 1 AND 128),
    scope_key TEXT COLLATE "C" NOT NULL CHECK (octet_length(scope_key) BETWEEN 1 AND 512),
    record_key TEXT COLLATE "C" NOT NULL CHECK (octet_length(record_key) BETWEEN 1 AND 200),
    generation TEXT COLLATE "C" NOT NULL CHECK (length(generation) = 36),
    expires_at_ms BIGINT,
    value_json TEXT COLLATE "C" NOT NULL CHECK (length(convert_to(value_json, 'UTF8')) <= 65536 AND value_json::jsonb IS NOT NULL),
    value_version INTEGER NOT NULL DEFAULT 1 CHECK (value_version BETWEEN 1 AND 2147483647),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CHECK (expires_at_ms IS NULL OR expires_at_ms > created_at_ms),
    PRIMARY KEY (plugin_id, collection, scope_key, record_key)
);

CREATE TABLE nuono_bot_instances (
    id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (octet_length(id) BETWEEN 1 AND 128),
    name TEXT COLLATE "C" NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 1 AND 128),
    platform TEXT COLLATE "C" NOT NULL CHECK (octet_length(platform) BETWEEN 1 AND 64),
    namespace TEXT COLLATE "C" NOT NULL DEFAULT '' CHECK (octet_length(namespace) <= 256),
    adapter_type TEXT COLLATE "C" NOT NULL CHECK (octet_length(adapter_type) BETWEEN 1 AND 64),
    native_bot_id TEXT COLLATE "C" CHECK (native_bot_id IS NULL OR octet_length(native_bot_id) BETWEEN 1 AND 256),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    config_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(config_json::jsonb) = 'object'),
    runtime_status TEXT COLLATE "C" NOT NULL DEFAULT 'offline' CHECK (runtime_status IN ('offline', 'online', 'error')),
    last_error TEXT COLLATE "C",
    last_connected_at_ms BIGINT,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CHECK (octet_length(platform || namespace || COALESCE(native_bot_id, '')) <= 1024)
);

CREATE TABLE nuono_filter_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    filter_type TEXT COLLATE "C" NOT NULL CHECK (length(filter_type) <= 20),
    pattern TEXT COLLATE "C" NOT NULL,
    match_mode TEXT COLLATE "C" NOT NULL DEFAULT 'simple' CHECK (length(match_mode) <= 10),
    target_id TEXT COLLATE "C" CHECK (target_id IS NULL OR length(target_id) <= 50),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at BIGINT DEFAULT ((extract(epoch FROM clock_timestamp()) * 1000)::BIGINT),
    CHECK (filter_type NOT IN ('blacklist_user', 'blacklist_group') OR (target_id IS NOT NULL AND target_id <> ''))
);

CREATE TABLE nuono_conversations (
    id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (octet_length(id) BETWEEN 1 AND 128),
    platform TEXT COLLATE "C" NOT NULL CHECK (octet_length(platform) BETWEEN 1 AND 64),
    bot_instance_id TEXT COLLATE "C" CHECK (bot_instance_id IS NULL OR octet_length(bot_instance_id) BETWEEN 1 AND 256),
    scope_type TEXT COLLATE "C" NOT NULL CHECK (scope_type IN ('web', 'private', 'group', 'group_user', 'thread')),
    group_id BIGINT REFERENCES nuono_groups(id) ON DELETE SET NULL,
    owner_user_id BIGINT REFERENCES nuono_users(id) ON DELETE SET NULL,
    native_chat_id TEXT COLLATE "C" NOT NULL DEFAULT '' CHECK (octet_length(native_chat_id) <= 1024),
    native_thread_id TEXT COLLATE "C" NOT NULL DEFAULT '' CHECK (octet_length(native_thread_id) <= 256),
    title TEXT COLLATE "C" CHECK (title IS NULL OR octet_length(title) <= 256),
    status TEXT COLLATE "C" NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived')),
    summary_text TEXT COLLATE "C",
    last_message_at_ms BIGINT,
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL
);

CREATE TABLE nuono_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    conversation_id TEXT COLLATE "C" REFERENCES nuono_conversations(id) ON DELETE SET NULL CHECK (conversation_id IS NULL OR octet_length(conversation_id) BETWEEN 1 AND 128),
    platform TEXT COLLATE "C" NOT NULL CHECK (octet_length(platform) BETWEEN 1 AND 64),
    bot_instance_id TEXT COLLATE "C" CHECK (bot_instance_id IS NULL OR octet_length(bot_instance_id) BETWEEN 1 AND 256),
    native_message_id TEXT COLLATE "C" CHECK (native_message_id IS NULL OR octet_length(native_message_id) BETWEEN 1 AND 512),
    reply_to_native_message_id TEXT COLLATE "C" CHECK (reply_to_native_message_id IS NULL OR octet_length(reply_to_native_message_id) BETWEEN 1 AND 512),
    sender_user_id BIGINT REFERENCES nuono_users(id) ON DELETE SET NULL,
    sender_identity_id BIGINT REFERENCES nuono_platform_identities(id) ON DELETE SET NULL,
    native_sender_id TEXT COLLATE "C" CHECK (native_sender_id IS NULL OR octet_length(native_sender_id) BETWEEN 1 AND 512),
    native_group_id TEXT COLLATE "C" CHECK (native_group_id IS NULL OR octet_length(native_group_id) BETWEEN 1 AND 512),
    sender_nickname TEXT COLLATE "C" CHECK (sender_nickname IS NULL OR length(sender_nickname) <= 100),
    direction TEXT COLLATE "C" NOT NULL CHECK (direction IN ('inbound', 'outbound')),
    role TEXT COLLATE "C" NOT NULL CHECK (role IN ('user', 'assistant', 'system')),
    text_content TEXT COLLATE "C" NOT NULL DEFAULT '',
    content_blocks_json TEXT COLLATE "C" NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(content_blocks_json::jsonb) = 'array'),
    raw_payload_json TEXT COLLATE "C",
    occurred_at_ms BIGINT NOT NULL,
    created_at_ms BIGINT NOT NULL
);

CREATE TABLE nuono_ai_runs (
    id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (octet_length(id) BETWEEN 1 AND 128),
    conversation_id TEXT COLLATE "C" NOT NULL REFERENCES nuono_conversations(id) ON DELETE CASCADE CHECK (octet_length(conversation_id) BETWEEN 1 AND 128),
    trigger_message_id BIGINT REFERENCES nuono_messages(id) ON DELETE SET NULL,
    reply_message_id BIGINT REFERENCES nuono_messages(id) ON DELETE SET NULL,
    user_id BIGINT REFERENCES nuono_users(id) ON DELETE SET NULL,
    provider TEXT COLLATE "C" NOT NULL DEFAULT '' CHECK (octet_length(provider) <= 128),
    model TEXT COLLATE "C" NOT NULL DEFAULT '' CHECK (octet_length(model) <= 256),
    status TEXT COLLATE "C" NOT NULL CHECK (status IN ('running', 'succeeded', 'failed', 'cancelled')),
    prompt_tokens INTEGER NOT NULL DEFAULT 0 CHECK (prompt_tokens >= 0),
    completion_tokens INTEGER NOT NULL DEFAULT 0 CHECK (completion_tokens >= 0),
    latency_ms INTEGER NOT NULL DEFAULT 0 CHECK (latency_ms >= 0),
    steps_json TEXT COLLATE "C" NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(steps_json::jsonb) = 'array'),
    error_message TEXT COLLATE "C",
    created_at_ms BIGINT NOT NULL,
    finished_at_ms BIGINT
);

CREATE TABLE nuono_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    category TEXT COLLATE "C" NOT NULL DEFAULT 'audit' CHECK (category IN ('audit', 'event', 'command')),
