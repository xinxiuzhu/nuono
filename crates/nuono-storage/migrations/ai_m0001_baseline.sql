-- Nuono 可选 AI / Agent / 陪伴模块表结构（PostgreSQL）。
-- 仅在启用 AI 或个人助手能力时按需安装。

CREATE TABLE nuono_ai_models (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    name TEXT COLLATE "C" NOT NULL CHECK (length(name) <= 100),
    provider TEXT COLLATE "C" NOT NULL CHECK (length(provider) <= 50),
    model_id TEXT COLLATE "C" NOT NULL CHECK (length(model_id) <= 200),
    api_key TEXT COLLATE "C",
    base_url TEXT COLLATE "C" NOT NULL CHECK (length(base_url) <= 500),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at BIGINT DEFAULT ((extract(epoch FROM clock_timestamp()) * 1000)::BIGINT),
    updated_at BIGINT DEFAULT ((extract(epoch FROM clock_timestamp()) * 1000)::BIGINT),
    provider_type TEXT COLLATE "C" NOT NULL DEFAULT 'openai_compatible' CHECK (length(provider_type) <= 30)
);

CREATE TABLE nuono_ai_usage_events (
    request_id TEXT COLLATE "C" PRIMARY KEY CHECK (length(request_id) <= 64),
    started_at_ms BIGINT NOT NULL,
    day TEXT COLLATE "C" NOT NULL CHECK (length(day) <= 10),
    model_id BIGINT,
    model TEXT COLLATE "C" NOT NULL CHECK (length(model) <= 256),
    name TEXT COLLATE "C" NOT NULL CHECK (length(name) <= 512),
    provider TEXT COLLATE "C" NOT NULL CHECK (length(provider) <= 256),
    source TEXT COLLATE "C" NOT NULL CHECK (length(source) <= 64),
    operation TEXT COLLATE "C" NOT NULL CHECK (length(operation) <= 32),
    outcome TEXT COLLATE "C" NOT NULL CHECK (length(outcome) <= 16),
    elapsed_ms BIGINT NOT NULL,
    input_tokens BIGINT,
    output_tokens BIGINT,
    total_tokens BIGINT,
    cached_input_tokens BIGINT,
    reasoning_output_tokens BIGINT
);

CREATE TABLE nuono_ai_personas (
    id TEXT COLLATE "C" PRIMARY KEY CHECK (length(id) <= 64),
    owner_user_id BIGINT REFERENCES nuono_users(id) ON DELETE CASCADE,
    name TEXT COLLATE "C" NOT NULL,
    description TEXT COLLATE "C" NOT NULL DEFAULT '',
    system_prompt TEXT COLLATE "C" NOT NULL DEFAULT '',
    user_address TEXT COLLATE "C" NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    avatar_filename TEXT COLLATE "C",
    portrait_filename TEXT COLLATE "C",
    reference_audio_filename TEXT COLLATE "C",
    reference_text TEXT COLLATE "C" NOT NULL DEFAULT '',
    language TEXT COLLATE "C" NOT NULL DEFAULT 'zh',
    tts_provider TEXT COLLATE "C",
    voice_id TEXT COLLATE "C",
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    updated_at BIGINT NOT NULL DEFAULT ((extract(epoch FROM clock_timestamp()) * 1000)::BIGINT)
);

CREATE TABLE nuono_ai_persona_bindings (
    target_key TEXT COLLATE "C" PRIMARY KEY CHECK (length(target_key) <= 64),
    platform TEXT COLLATE "C" NOT NULL,
    bot_id TEXT COLLATE "C" NOT NULL,
    group_id TEXT COLLATE "C" NOT NULL,
    namespace TEXT COLLATE "C",
    persona_id TEXT COLLATE "C" NOT NULL REFERENCES nuono_ai_personas(id) ON DELETE RESTRICT CHECK (length(persona_id) <= 64)
);

CREATE TABLE nuono_account_assistant (
    user_id BIGINT PRIMARY KEY REFERENCES nuono_users(id) ON DELETE CASCADE,
    grant_until BIGINT,
    grant_daily_limit INTEGER CHECK (grant_daily_limit BETWEEN 1 AND 500),
    usage_day BIGINT NOT NULL DEFAULT -1,
    request_ids TEXT COLLATE "C" NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(request_ids::jsonb) = 'array'),
    active_card_id TEXT COLLATE "C",
    context_epochs_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(context_epochs_json::jsonb) = 'object'),
    CHECK ((grant_until IS NULL) = (grant_daily_limit IS NULL))
);

CREATE TABLE nuono_assistant_turns (
    id TEXT COLLATE "C" PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES nuono_users(id) ON DELETE CASCADE,
    conversation_id TEXT COLLATE "C" REFERENCES nuono_conversations(id) ON DELETE SET NULL CHECK (conversation_id IS NULL OR octet_length(conversation_id) BETWEEN 1 AND 128),
    card_id TEXT COLLATE "C" NOT NULL,
    scope_key TEXT COLLATE "C" NOT NULL,
    context_epoch BIGINT NOT NULL DEFAULT 0,
    prompt_snapshot TEXT COLLATE "C" NOT NULL DEFAULT '',
    redacted BOOLEAN NOT NULL DEFAULT FALSE,
    control BOOLEAN NOT NULL DEFAULT FALSE,
    compacted BOOLEAN NOT NULL DEFAULT FALSE,
    request_key TEXT COLLATE "C" NOT NULL,
    text TEXT COLLATE "C" NOT NULL,
    retry_of TEXT COLLATE "C",
    status TEXT COLLATE "C" NOT NULL CHECK (status IN ('running', 'succeeded', 'failed', 'interrupted')),
    failure TEXT COLLATE "C",
    reply TEXT COLLATE "C",
    quota_day BIGINT NOT NULL,
    delivery TEXT COLLATE "C" NOT NULL CHECK (delivery IN ('none', 'pending', 'sent', 'unknown')),
    delivery_key TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    UNIQUE (user_id, request_key),
    UNIQUE (user_id, retry_of)
);

CREATE TABLE nuono_agent_runs (
    id TEXT COLLATE "C" PRIMARY KEY CHECK (length(id) <= 64),
    conversation_id TEXT COLLATE "C" REFERENCES nuono_conversations(id) ON DELETE SET NULL CHECK (conversation_id IS NULL OR octet_length(conversation_id) BETWEEN 1 AND 128),
    session_id TEXT COLLATE "C" NOT NULL,
    status TEXT COLLATE "C" NOT NULL CHECK (length(status) <= 32),
    state_json TEXT COLLATE "C" NOT NULL CHECK (state_json::jsonb IS NOT NULL),
    approval_id BIGINT,
    revision BIGINT NOT NULL DEFAULT 0,
    updated_at BIGINT NOT NULL DEFAULT ((extract(epoch FROM clock_timestamp()) * 1000)::BIGINT),
    parent_id TEXT COLLATE "C" REFERENCES nuono_agent_runs(id) CHECK (parent_id IS NULL OR length(parent_id) <= 64)
);

CREATE TABLE nuono_agent_policy_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    effect TEXT COLLATE "C" NOT NULL,
    target_type TEXT COLLATE "C" NOT NULL,
    target_value TEXT COLLATE "C" NOT NULL,
    priority INTEGER NOT NULL DEFAULT 100 CHECK (priority BETWEEN -2147483648 AND 2147483647),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    reason TEXT COLLATE "C",
    created_by TEXT COLLATE "C",
    updated_by TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE nuono_agent_tool_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    session_id TEXT COLLATE "C" NOT NULL,
    bot_id BIGINT NOT NULL,
    platform TEXT COLLATE "C" NOT NULL,
    message_type TEXT COLLATE "C" NOT NULL,
    user_id BIGINT NOT NULL,
    group_id BIGINT,
    channel_id TEXT COLLATE "C",
    message_id TEXT COLLATE "C",
    tool_name TEXT COLLATE "C" NOT NULL,
    risk_level TEXT COLLATE "C" NOT NULL,
    status TEXT COLLATE "C" NOT NULL,
    input_json TEXT COLLATE "C" CHECK (input_json IS NULL OR input_json::jsonb IS NOT NULL),
    reason TEXT COLLATE "C",
    decision_by TEXT COLLATE "C",
    decision_reason TEXT COLLATE "C",
    decided_at BIGINT,
    created_at BIGINT NOT NULL,
    context_json TEXT COLLATE "C" CHECK (context_json IS NULL OR context_json::jsonb IS NOT NULL),
    execution_json TEXT COLLATE "C" CHECK (execution_json IS NULL OR execution_json::jsonb IS NOT NULL),
    run_id TEXT COLLATE "C" CHECK (run_id IS NULL OR length(run_id) <= 64)
);

CREATE TABLE nuono_agent_tool_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    session_id TEXT COLLATE "C" NOT NULL,
    bot_id BIGINT NOT NULL,
    platform TEXT COLLATE "C" NOT NULL,
    message_type TEXT COLLATE "C" NOT NULL,
    user_id BIGINT NOT NULL,
    group_id BIGINT,
    channel_id TEXT COLLATE "C",
    message_id TEXT COLLATE "C",
    tool_name TEXT COLLATE "C" NOT NULL,
    risk_level TEXT COLLATE "C" NOT NULL,
    status TEXT COLLATE "C" NOT NULL,
    input_json TEXT COLLATE "C" CHECK (input_json IS NULL OR input_json::jsonb IS NOT NULL),
    output_json TEXT COLLATE "C" CHECK (output_json IS NULL OR output_json::jsonb IS NOT NULL),
    error TEXT COLLATE "C",
    elapsed_ms INTEGER NOT NULL DEFAULT 0 CHECK (elapsed_ms BETWEEN -2147483648 AND 2147483647),
    created_at BIGINT NOT NULL,
    context_json TEXT COLLATE "C" CHECK (context_json IS NULL OR context_json::jsonb IS NOT NULL)
);

CREATE TABLE nuono_agent_memories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    scope_type TEXT COLLATE "C" NOT NULL,
    scope_key TEXT COLLATE "C" NOT NULL,
    memory_key TEXT COLLATE "C" NOT NULL,
    content TEXT COLLATE "C" NOT NULL,
    tags_json TEXT COLLATE "C" CHECK (tags_json IS NULL OR tags_json::jsonb IS NOT NULL),
    pinned BOOLEAN,
    recall_count BIGINT NOT NULL DEFAULT 0 CHECK (recall_count >= 0),
    last_recalled_at BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_by TEXT COLLATE "C",
    updated_by TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    expires_at BIGINT,
    CHECK (pinned IS NOT NULL OR (recall_count = 0 AND last_recalled_at IS NULL))
);

CREATE TABLE nuono_agent_memory_embeddings (
    memory_id BIGINT NOT NULL REFERENCES nuono_agent_memories(id) ON DELETE CASCADE,
    model_id BIGINT NOT NULL CHECK (model_id > 0),
    model_name TEXT COLLATE "C" NOT NULL CHECK (octet_length(model_name) BETWEEN 1 AND 512),
    model_revision TEXT COLLATE "C" NOT NULL CHECK (octet_length(model_revision) BETWEEN 1 AND 128),
    content_fingerprint TEXT COLLATE "C" NOT NULL CHECK (length(content_fingerprint) = 64),
    dimensions INTEGER NOT NULL CHECK (dimensions BETWEEN 1 AND 4096),
    vector_json TEXT COLLATE "C" NOT NULL CHECK (octet_length(vector_json) <= 65536 AND vector_json::jsonb IS NOT NULL),
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (memory_id, model_id)
);

CREATE TABLE nuono_agent_memory_graphs (
    scope_type TEXT COLLATE "C" NOT NULL,
    scope_key TEXT COLLATE "C" NOT NULL,
    source_fingerprint TEXT COLLATE "C" NOT NULL,
    source_limit INTEGER NOT NULL CHECK (source_limit BETWEEN 2 AND 128),
    graph_json TEXT COLLATE "C" NOT NULL CHECK (graph_json::jsonb IS NOT NULL),
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (scope_type, scope_key)
);

CREATE TABLE nuono_companion_memory_sources (
    memory_id BIGINT NOT NULL REFERENCES nuono_agent_memories(id) ON DELETE CASCADE,
    source_id TEXT COLLATE "C" NOT NULL,
    scope_key TEXT COLLATE "C" NOT NULL,
    detail TEXT COLLATE "C" NOT NULL CHECK (detail IN ('full', 'summary', 'outline')),
    original TEXT COLLATE "C" NOT NULL CHECK (original IN ('available', 'reclaimed', 'deleted')),
    importance DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    observed_at BIGINT NOT NULL,
    PRIMARY KEY (memory_id, source_id)
);

CREATE INDEX idx_ai_personas_owner ON nuono_ai_personas (owner_user_id, id);
CREATE INDEX ai_persona_bindings_persona ON nuono_ai_persona_bindings (persona_id);
CREATE INDEX idx_assistant_turns_account ON nuono_assistant_turns (user_id, created_at DESC, id);
CREATE INDEX idx_assistant_turns_pending ON nuono_assistant_turns (status, user_id);
CREATE INDEX idx_assistant_turns_conversation ON nuono_assistant_turns (conversation_id) WHERE conversation_id IS NOT NULL;
CREATE INDEX idx_companion_sources_scope ON nuono_companion_memory_sources (scope_key, source_id);
CREATE INDEX idx_ai_usage_started_at ON nuono_ai_usage_events (started_at_ms);
CREATE INDEX idx_ai_usage_model_started_at ON nuono_ai_usage_events (model_id, started_at_ms);
CREATE INDEX idx_agent_memories_enabled ON nuono_agent_memories (enabled);
CREATE INDEX idx_agent_memories_expires_at ON nuono_agent_memories (expires_at);
CREATE UNIQUE INDEX idx_agent_memories_unique_key ON nuono_agent_memories (scope_type, scope_key, memory_key);
CREATE INDEX idx_agent_policy_rules_enabled ON nuono_agent_policy_rules (enabled);
CREATE INDEX idx_agent_tool_approvals_status ON nuono_agent_tool_approvals (status);
CREATE INDEX idx_agent_tool_receipts_session_id ON nuono_agent_tool_receipts (session_id);
CREATE UNIQUE INDEX agent_runs_approval ON nuono_agent_runs (approval_id) WHERE approval_id IS NOT NULL;
CREATE INDEX agent_runs_parent ON nuono_agent_runs (parent_id);
CREATE INDEX idx_agent_runs_conversation ON nuono_agent_runs (conversation_id) WHERE conversation_id IS NOT NULL;
CREATE UNIQUE INDEX agent_runs_active_session ON nuono_agent_runs (session_id)
    WHERE status IN ('queued', 'running', 'waiting_approval', 'waiting_children');
