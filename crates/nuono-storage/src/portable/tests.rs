#[tokio::test]
#[ignore = "requires isolated PostgreSQL CREATEDB access via NUONO_TEST_DATABASE_URL"]
async fn postgres_refuses_unregistered_objects_before_export_or_import() {
    let admin_url =
        std::env::var("NUONO_TEST_DATABASE_URL").expect("set test PostgreSQL admin URL explicitly");
    let admin = sea_orm::Database::connect(admin_url.clone()).await.unwrap();
    let name = format!("nuono_test_{}", uuid::Uuid::new_v4().simple());
    admin
        .execute_unprepared(&format!("CREATE DATABASE \"{name}\""))
        .await
        .unwrap();
    let mut url = url::Url::parse(&admin_url).unwrap();
    url.set_path(&format!("/{name}"));
    let pg = raw_connection(url.as_str()).await;
    let sqlite_source = populated().await;
    let schema = fixture();
    let image = export(&sqlite_source, &schema).await.unwrap();
    let cases = [
        (
            "empty_private",
            "CREATE SCHEMA empty_private",
            "DROP SCHEMA empty_private",
        ),
        (
            "private_data",
            "CREATE SCHEMA private_data; CREATE TABLE private_data.orders(id BIGINT PRIMARY KEY); INSERT INTO private_data.orders VALUES(1)",
            "DROP TABLE private_data.orders; DROP SCHEMA private_data",
        ),
        (
            "独立序列",
            "CREATE SEQUENCE public.extra_sequence",
            "DROP SEQUENCE public.extra_sequence",
        ),
        (
            "extra_routine",
            "CREATE FUNCTION public.extra_routine() RETURNS BIGINT LANGUAGE SQL AS 'SELECT 1::BIGINT'",
            "DROP FUNCTION public.extra_routine()",
        ),
        (
            "extra_enum",
            "CREATE TYPE public.extra_enum AS ENUM('paid','unpaid')",
            "DROP TYPE public.extra_enum",
        ),
        (
            "extra_domain",
            "CREATE DOMAIN public.extra_domain AS BIGINT CHECK(VALUE>0)",
            "DROP DOMAIN public.extra_domain",
        ),
        (
            "extra_composite",
            "CREATE TYPE public.extra_composite AS (amount BIGINT)",
            "DROP TYPE public.extra_composite",
        ),
        (
            "extra_collation",
            "CREATE COLLATION public.extra_collation (provider=libc,locale='C')",
            "DROP COLLATION public.extra_collation",
        ),
        (
            "extra_search",
            "CREATE TEXT SEARCH CONFIGURATION public.extra_search (COPY=pg_catalog.simple)",
            "DROP TEXT SEARCH CONFIGURATION public.extra_search",
        ),
        (
            "large object",
            "SELECT lo_create(0)",
            "SELECT lo_unlink(oid) FROM pg_largeobject_metadata",
        ),
    ];
    for (label, create, remove) in cases {
        pg.execute_unprepared(create).await.unwrap();
        let error = preflight_import(&pg, &schema, &image).await.unwrap_err();
        assert!(error.to_string().contains(label), "{label}: {error}");
        assert!(import(&pg, &schema, &image).await.is_err(), "{label}");
        pg.execute_unprepared(remove).await.unwrap();
    }
    preflight_import(&pg, &schema, &image).await.unwrap();
    import(&pg, &schema, &image).await.unwrap();
    // 已登记自增列对应的序列以及建表时自动生成的同名复合行类型/数组类型均属合法对象。
    assert_eq!(export(&pg, &schema).await.unwrap(), image);
    for (label, create, remove) in cases {
        pg.execute_unprepared(create).await.unwrap();
        let error = export(&pg, &schema).await.unwrap_err();
        assert!(error.to_string().contains(label), "{label}: {error}");
        pg.execute_unprepared(remove).await.unwrap();
    }
    // 触发器与表拥有各自独立的命名空间：与表同名的触发器不得在集合去重时被表名掩盖；调用 pg_catalog 内置函数仍必须被识别并拒绝导出。
    pg.execute_unprepared("CREATE TRIGGER fixture BEFORE UPDATE ON fixture FOR EACH ROW EXECUTE FUNCTION pg_catalog.suppress_redundant_updates_trigger()")
        .await
        .unwrap();
    let error = export(&pg, &schema).await.unwrap_err();
    assert!(
        error.to_string().contains("trigger public.fixture.fixture"),
        "{error}"
    );
    pg.execute_unprepared("DROP TRIGGER fixture ON fixture")
        .await
        .unwrap();
    pg.execute_unprepared("ALTER TABLE fixture ENABLE ROW LEVEL SECURITY")
        .await
        .unwrap();
    let error = export(&pg, &schema).await.unwrap_err();
    assert!(error.to_string().contains("row security"), "{error}");
    pg.execute_unprepared("ALTER TABLE fixture DISABLE ROW LEVEL SECURITY")
        .await
        .unwrap();
    assert_eq!(export(&pg, &schema).await.unwrap(), image);
    sqlite_source.close().await.unwrap();
    pg.close().await.unwrap();
    admin
        .execute_unprepared(&format!("DROP DATABASE \"{name}\""))
        .await
        .unwrap();
    admin.close().await.unwrap();
}

