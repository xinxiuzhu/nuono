async fn raw_connection(url: &str) -> DatabaseConnection {
    let mut options = ConnectOptions::new(url);
    options
        .max_connections(1)
        .min_connections(1)
        .sqlx_logging(false);
    let connection = sea_orm::Database::connect(options).await.unwrap();
    if connection.get_database_backend() == DbBackend::Sqlite {
        connection
            .execute_unprepared("PRAGMA foreign_keys=ON")
            .await
            .unwrap();
    }
    connection
}

async fn initialized_connection(url: &str) -> crate::Database {
    crate::Database::from_config(&crate::config::DatabaseConfig {
        url: url.into(),
        max_connections: 1,
    })
    .await
    .unwrap()
}

