fn workspace(label: &str) -> PathBuf {
    let path =
        std::env::temp_dir().join(format!("nuono-portable-{label}-{}", uuid::Uuid::new_v4()));
    fs::create_dir(&path).unwrap();
    path.canonicalize().unwrap()
}

fn declaration() -> PluginStorageDeclaration {
    let postgres = "CREATE TABLE portable_demo_rows(id BIGINT PRIMARY KEY,amount BIGINT NOT NULL CHECK(amount>=0),label TEXT NOT NULL UNIQUE); CREATE INDEX portable_demo_amount ON portable_demo_rows(amount);";
    let sqlite = "CREATE TABLE portable_demo_rows(id INTEGER PRIMARY KEY,amount INTEGER NOT NULL CHECK(amount>=0),label TEXT NOT NULL UNIQUE) STRICT; CREATE INDEX portable_demo_amount ON portable_demo_rows(amount);";
    let mut manifest = PortableManifest::empty("portable_demo");
    manifest.postgres_schema = postgres.into();
    manifest.sqlite_schema = sqlite.into();
    PluginStorageDeclaration {
        manifest,
        versions: vec![PluginStorageVersion {
            version: 1,
            description: "initial".into(),
            postgres_sql: postgres.into(),
            sqlite_sql: sqlite.into(),
        }],
    }
}

#[test]
fn strict_documents_reject_duplicate_metadata_and_nonportable_scalars() {
    assert!(parse_document::<serde_json::Value>(br#"{"id":1,"id":2}"#).is_err());
    assert!(parse_document::<serde_json::Value>(br#"{"id":9223372036854775808}"#).is_err());
    let accepted: serde_json::Value =
        parse_document(br#"{"id":9007199254740993,"zero":0,"empty":"","null":null,"flag":false}"#)
            .unwrap();
    assert_eq!(accepted["id"].as_i64(), Some(9_007_199_254_740_993));
    let mut manifest = declaration().manifest;
    manifest.postgres_schema =
        "CREATE TABLE portable_demo_rows(id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY)"
            .into();
    manifest.sqlite_schema =
        "CREATE TABLE portable_demo_rows(id INTEGER PRIMARY KEY AUTOINCREMENT) STRICT".into();
    assert!(manifest_tables(&manifest).is_err());
    manifest.postgres_schema="CREATE TABLE portable_demo_rows(id BIGINT GENERATED BY DEFAULT AS IDENTITY (START 10) PRIMARY KEY)".into();
    assert!(manifest_tables(&manifest).is_err());
}

#[tokio::test]
async fn ledger_preserves_retained_tables_and_rejects_immutable_version_edits() {
    let db = crate::test_support::test_db(2).await;
    let mut declared = declaration();
    db.register_plugin_storage("portable_demo", "1.0", &declared)
        .await
        .unwrap();
    let index = "CREATE INDEX portable_demo_label ON portable_demo_rows(label);";
    declared.manifest.postgres_schema.push_str(index);
    declared.manifest.sqlite_schema.push_str(index);
    declared.versions.push(PluginStorageVersion {
        version: 2,
        description: "seed exactly once".into(),
        postgres_sql: format!("{index} INSERT INTO portable_demo_rows VALUES(1,3,'once')"),
        sqlite_sql: format!("{index} INSERT INTO portable_demo_rows VALUES(1,3,'once')"),
    });
    let (first, second) = tokio::join!(
        db.register_plugin_storage("portable_demo", "1.1", &declared),
        db.register_plugin_storage("portable_demo", "1.1", &declared)
    );
    first.unwrap();
    second.unwrap();
    db.mark_plugin_code_absent("portable_demo").await.unwrap();
    let retained = registered_plugins(db.orm()).await.unwrap();
    assert_eq!(retained.len(), 1);
    assert!(!retained[0].installed);
    assert_eq!(retained[0].version, Some(2));
    let schema = registered_schema(db.orm()).await.unwrap();
    let image = export(db.orm(), &schema).await.unwrap();
    assert_eq!(
        image
            .tables
            .iter()
            .find(|t| t.definition.name == "portable_demo_rows")
            .unwrap()
            .rows
            .len(),
        1
    );
    let target = super::tests::sqlite().await;
    import(&target, &Schema::from_image(&image).unwrap(), &image)
        .await
        .unwrap();
    verify(&target, &schema, &image).await.unwrap();
    assert_eq!(registered_plugins(&target).await.unwrap(), retained);
    let mut corrupt = declared.clone();
    corrupt.versions[0]
        .sqlite_sql
        .push_str(" -- edited published history");
    assert!(
        db.register_plugin_storage("portable_demo", "1.1", &corrupt)
            .await
            .is_err()
    );
    let mut metadata = image.clone();
    metadata.deployment.as_mut().unwrap().plugins[0].code_version = Some("tampered".into());
    let empty = super::tests::sqlite().await;
    assert!(import(&empty, &schema, &metadata).await.is_err());
    assert!(
        empty
            .query_all_raw(Statement::from_string(
                DbBackend::Sqlite,
                "SELECT name FROM sqlite_schema WHERE name NOT GLOB 'sqlite_*'"
            ))
            .await
            .unwrap()
            .is_empty()
    );
    db.orm()
        .execute_unprepared("UPDATE nuono_schema_migrations SET checksum='tampered'")
        .await
        .unwrap();
    assert!(registered_schema(db.orm()).await.is_err());
    target.close().await.unwrap();
    empty.close().await.unwrap();
    db.shutdown().await.unwrap();
}

#[tokio::test]
async fn live_constraints_indexes_and_defaults_cannot_drift_silently() {
    let db = crate::test_support::test_db(2).await;
    db.register_plugin_storage("portable_demo", "1", &declaration())
        .await
        .unwrap();
    let schema = registered_schema(db.orm()).await.unwrap();
    db.orm()
        .execute_unprepared("DROP INDEX portable_demo_amount")
        .await
        .unwrap();
    assert!(export(db.orm(), &schema).await.is_err());
    assert!(
        db.register_plugin_storage("portable_demo", "1", &declaration())
            .await
            .is_err()
    );
    db.shutdown().await.unwrap();
    for sqlite_sql in [
        "CREATE TABLE probe(id INTEGER PRIMARY KEY,value INTEGER NOT NULL CHECK(value>=0),label TEXT NOT NULL UNIQUE) STRICT",
        "CREATE TABLE probe(id INTEGER PRIMARY KEY,value INTEGER NOT NULL DEFAULT 8 CHECK(value>0),label TEXT NOT NULL UNIQUE) STRICT",
        "CREATE TABLE probe(id INTEGER PRIMARY KEY,value INTEGER NOT NULL CHECK(value>0),label TEXT NOT NULL) STRICT",
    ] {
        let schema=Schema::new(vec![Migration{name:"constraint-probe".into(),postgres_sql:"CREATE TABLE probe(id BIGINT PRIMARY KEY,value BIGINT NOT NULL CHECK(value>0),label TEXT NOT NULL UNIQUE)".into(),sqlite_sql:"CREATE TABLE probe(id INTEGER PRIMARY KEY,value INTEGER NOT NULL CHECK(value>0),label TEXT NOT NULL UNIQUE) STRICT".into()}]).unwrap();
        let conn = super::tests::sqlite().await;
        conn.execute_unprepared(sqlite_sql).await.unwrap();
        assert!(export(&conn, &schema).await.is_err());
        conn.close().await.unwrap();
    }
}

#[tokio::test]
async fn external_files_are_complete_resumable_and_reference_config_is_not_restored() {
    let root = workspace("external");
    let data = root.join("source");
    let target = root.join("target");
    fs::create_dir(&data).unwrap();
    fs::create_dir(&target).unwrap();
    let secret = root.join("secret.bin");
    let config = root.join("source.toml");
    fs::write(&secret, [0, 255, 2]).unwrap();
    fs::write(&config, b"source URL reference").unwrap();
    let db = crate::test_support::test_db(1).await;
    db.register_deployment_assets(&[
        PersistentAsset::External {
            key: "secret".into(),
            path: secret.to_string_lossy().into_owned(),
            required: true,
        },
        PersistentAsset::Reference {
            key: "config".into(),
            path: config.to_string_lossy().into_owned(),
            required: true,
        },
    ])
    .await
    .unwrap();
    let image = export(db.orm(), &registered_schema(db.orm()).await.unwrap())
        .await
        .unwrap();
    let package = root.join("package");
    files::write_package(&package, &data, None, &image).unwrap();
    let (manifest, read) = files::read_package(&package).unwrap();
    assert_eq!(read, image);
    assert_eq!(manifest.external.len(), 2);
    assert!(external::preflight(&target, &manifest.external, &BTreeMap::new()).is_err());
    let output = root.join("target-secret.bin");
    let targets = BTreeMap::from([("nuono/secret".into(), output.clone())]);
    external::stage(
        &package.join("external"),
        &target,
        &manifest.database_sha256,
        &manifest.external,
        &targets,
    )
    .unwrap();
    let staged = target
        .join(external::STAGING)
        .join(hex::encode(sha2::Sha256::digest(b"nuono/secret")))
        .join("value");
    fs::write(&staged, b"partial").unwrap();
    external::stage(
        &package.join("external"),
        &target,
        &manifest.database_sha256,
        &manifest.external,
        &targets,
    )
    .unwrap();
    external::publish(&target, &manifest.database_sha256).unwrap();
    external::verify_published(&target, &manifest.database_sha256, &manifest.external).unwrap();
    assert_eq!(fs::read(output).unwrap(), [0, 255, 2]);
    assert_eq!(fs::read(config).unwrap(), b"source URL reference");
    fs::remove_file(secret).unwrap();
    assert!(files::write_package(&root.join("missing"), &data, None, &image).is_err());
    db.shutdown().await.unwrap();
    fs::remove_dir_all(root).unwrap();
}

#[tokio::test]
async fn purge_removes_owned_schema_and_ledger_together_then_allows_reinstall() {
    let root = workspace("purge");
    let data = root.join("data");
    fs::create_dir_all(data.join("portable_demo")).unwrap();
    fs::write(data.join("portable_demo/state.bin"), [1, 2, 3]).unwrap();
    let db = crate::test_support::test_db(1).await;
    let declaration = declaration();
    db.register_plugin_storage("portable_demo", "1", &declaration)
        .await
        .unwrap();
    let preview = purge::plan(db.orm(), "portable_demo", &data).await.unwrap();
    assert_eq!(preview.tables, ["portable_demo_rows"]);
    assert_eq!(preview.files.len(), 1);
    db.orm()
        .execute_unprepared("INSERT INTO portable_demo_rows VALUES(1,0,'after-preview')")
        .await
        .unwrap();
    assert!(purge::apply(db.orm(), &data, &preview).await.is_err());
    let preview = purge::plan(db.orm(), "portable_demo", &data).await.unwrap();
    purge::apply(db.orm(), &data, &preview).await.unwrap();
    assert!(!data.join("portable_demo").exists());
    assert!(!data.join(purge::PENDING).exists());
    let registered = registered_plugins(db.orm()).await.unwrap();
    assert_eq!(registered[0].version, None);
    assert!(registered[0].installed);
    db.register_plugin_storage("portable_demo", "1", &declaration)
        .await
        .unwrap();
    assert_eq!(
        registered_plugins(db.orm()).await.unwrap()[0].version,
        Some(1)
    );
    assert_eq!(
        db.orm()
            .query_one_raw(Statement::from_string(
                db.backend(),
                "SELECT COUNT(*) AS n FROM portable_demo_rows"
            ))
            .await
            .unwrap()
            .unwrap()
            .try_get::<i64>("", "n")
            .unwrap(),
        0
    );
    let again = purge::plan(db.orm(), "portable_demo", &data).await.unwrap();
    purge::apply(db.orm(), &data, &again).await.unwrap();
    db.shutdown().await.unwrap();
    fs::remove_dir_all(root).unwrap();
}

#[tokio::test]
async fn purge_refuses_foreign_dependencies_and_shared_external_assets() {
    let root = workspace("purge-dependency");
    let data = root.join("data");
    fs::create_dir(&data).unwrap();
    let db = crate::test_support::test_db(1).await;
    let mut own = declaration();
    let shared = root.join("shared.bin");
    fs::write(&shared, b"shared").unwrap();
    own.manifest.assets.push(PersistentAsset::External {
        key: "shared".into(),
        path: shared.to_string_lossy().into_owned(),
        required: true,
    });
    db.register_plugin_storage("portable_demo", "1", &own)
        .await
        .unwrap();
    db.register_deployment_assets(&[PersistentAsset::Reference {
        key: "shared-config".into(),
        path: shared.to_string_lossy().into_owned(),
        required: true,
    }])
    .await
    .unwrap();
    assert!(purge::plan(db.orm(), "portable_demo", &data).await.is_err());
    db.register_deployment_assets(&[]).await.unwrap();
    let other=PluginStorageDeclaration::from_migrations("other",vec![nuono_app::plugin_data::PluginMigrationForBackend{version:1,description:"dependency".into(),pg_sql:"CREATE TABLE other_links(id BIGINT PRIMARY KEY,demo_id BIGINT REFERENCES portable_demo_rows(id))".into(),sqlite_sql:"CREATE TABLE other_links(id INTEGER PRIMARY KEY,demo_id INTEGER REFERENCES portable_demo_rows(id)) STRICT".into()}]).unwrap();
    db.register_plugin_storage("other", "1", &other)
        .await
        .unwrap();
    let preview = purge::plan(db.orm(), "portable_demo", &data).await.unwrap();
    assert_eq!(preview.dependencies.len(), 1);
    assert!(purge::apply(db.orm(), &data, &preview).await.is_err());
    db.shutdown().await.unwrap();
    fs::remove_dir_all(root).unwrap();
}
